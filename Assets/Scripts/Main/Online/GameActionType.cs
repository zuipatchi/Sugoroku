namespace Main.Online
{
    /// <summary>
    /// ゲームを進める「決定」の種別。手番の人（あるいは着地した人・アイテムを使った人）が決めて
    /// <see cref="OnlineGameSync.Publish"/> し、全クライアントが受信した順に適用する。
    /// ルーレットの出目によるコマ移動・陣地占拠・勝敗判定は、停止セクターと盤面から決定論的に導けるため送らない。
    /// 逆に、着地のたびに乱数で決まるもの（お金の増減額・進む／戻るのマス数・ショップの品揃え）は
    /// 決定論的に導けないので、決めた 1 人が配って全員がその値を適用する。
    /// </summary>
    public enum GameActionType
    {
        /// <summary>
        /// ルーレットの停止位置が確定した（＝手番の人が押下を離した）。
        /// 引数 0 = 停止セクター index、引数 1 = 減速時間（ミリ秒）。
        /// 円盤が止まる**前**に配られるので、受信側も同じタイミングで減速に入れる。
        /// </summary>
        Spin = 0,

        /// <summary>お金マスへの着地。引数 0 = 所持金の増減額（符号付き）。</summary>
        MoneyLanding = 1,

        /// <summary>アイテムショップの購入結果。引数 0 = 買った <see cref="Item.ItemId"/>（買わなかったら負値）。</summary>
        ShopResult = 2,

        /// <summary>アイテム使用。引数 0 = <see cref="Item.ItemId"/>、引数 1 以降 = 効果パラメータ。</summary>
        ItemUse = 3,

        /// <summary>退出通知（対戦の続行が不可能になったことを伝える）。</summary>
        Leave = 4,

        /// <summary>
        /// ルーレットを回し始めた（手番の人が押した／CPU が回し出した）合図。引数なし。
        /// 受け取ったクライアントは自分の円盤も回し始め、<see cref="Spin"/> が届くまで回し続ける
        /// （相手が回している間こちらの画面が止まって見えるのを防ぐ）。
        /// </summary>
        SpinStart = 5,

        /// <summary>
        /// 待機表示の切り替え。引数 0 = <see cref="BusyReason"/>（<see cref="BusyReason.None"/> なら解除）。
        /// 盤面を進める決定ではなく「いま自分の手元で時間のかかる操作をしている」というお知らせで、
        /// モーダルやミニゲームを開く前に配って、他のクライアントに待機表示を出してもらう。
        /// </summary>
        Busy = 6,

        /// <summary>
        /// ミニゲームマスへの着地。引数 0 = 遊ぶ <see cref="Common.MiniGame.MiniGameId"/>、
        /// 引数 1 = ゲームの内容を組み立てる種。
        /// 着地した人が両方を配り、**全員が同じゲームの同じ内容を同時に遊ぶ**（オンライン）。
        /// **遊ぶゲームは着地のたびの抽選**（<see cref="Common.MiniGame.MiniGameCatalog.RandomGame"/>）なので、
        /// マスのデータからは導けず配る必要がある。
        /// </summary>
        MiniGameLanding = 7,

        /// <summary>
        /// ミニゲームの自分の結果値。引数 0 = 生の結果値（連打数・ゴールタイム・選んだカード index）。
        /// 全参加者ぶんが揃ったら <see cref="Common.MiniGame.MiniGameRanking"/> で勝者を決めるので、
        /// 誰かが判定役になる必要は無い（全クライアントが同じ結論に至る）。
        /// </summary>
        MiniGameScore = 8,

        /// <summary>
        /// 進む／戻るマスへの着地。引数 0 = 続けて動くマス数（進む＝正・戻る＝負）。
        /// マス数は盤面データではなく着地のたびのランダム（<see cref="Board.MoveCellRule"/>）なので、
        /// 着地した本人が決めて配り、全員が受信した値で同じ連鎖を再現する。
        /// 値は末尾に足す規約なので、下の制御メッセージの続きの番号になる。
        /// </summary>
        MoveLanding = 12,

        /// <summary>
        /// ミニゲームの「はじめる」を押した（引数なし）。ミニゲームマスに着地すると全クライアントが
        /// 遊ぶゲームの告知とボタンを出し、**参加者全員ぶんが揃ってから**起動する
        /// （準備できていない人を置き去りにして始めないため）。
        /// 一人用モードは CPU がボタンを押せないので、自分が押した時点で全席ぶんを配る。
        /// </summary>
        MiniGameReady = 13,

        // ─────────────────────────────────────────────────────────────
        // ここから下は「制御メッセージ」。盤面を進める決定ではないので ActionStream には載せず、
        // 専用の別チャンネルで送って受信側が即座に処理する（進行との順序付けが要らないため）。
        // 進行を待っている側（GameFlowController / BoardPresenter）は触らなくてよい。
        // ─────────────────────────────────────────────────────────────

        /// <summary>
        /// 席 <c>Seat</c> のプレイヤーが切断した＝進行を一時停止する。引数 0 = 復帰を待つ残り秒数。
        /// 切断を検知したホストが配る。受け取った全員は入力を止めて再接続を待つ。
        /// </summary>
        Pause = 9,

        /// <summary>
        /// 席 <c>Seat</c> のプレイヤーが復帰した＝一時停止を解除する。引数なし。
        /// 差分の再送（取りこぼしたアクション）を送り終えたホストが最後に配る。
        /// </summary>
        Resume = 10,

        /// <summary>
        /// 復帰したクライアントからホストへの「ここまで受け取った」申告。引数 0 = 受信済みの最後の seq。
        /// 受け取ったホストは、それより後のアクションをログから順に送り直してから <see cref="Resume"/> を配る。
        /// </summary>
        Resync = 11,
    }
}
